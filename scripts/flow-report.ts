// User flow coverage report and guard. Run after the full browser test suite.
//
//   node scripts/flow-report.ts           report, and fail if a flow-device pair lost its test (CI)
//   node scripts/flow-report.ts --update  also accept today's coverage as the baseline,
//                                         and regenerate docs/user-flows.md
//   ... --update --allow-drop             accept a baseline that drops pairs (say why in the PR)
//
// The flow list is e2e/flows.json. e2e/flow-reporter.ts records which tests proved which flows.
// A flow is covered on a device only when it passes in every browser project for that device.
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';

const FLOWS = 'e2e/flows.json';
const RESULTS = 'test-results/flows.json';
const BASELINE = 'e2e/flow-baseline.json';
const DOC = 'docs/user-flows.md';

type Device = 'desktop' | 'phone';
interface Flow {
	id: string;
	name: string;
	devices: Device[];
	stories: string;
}
interface FlowList {
	devices: Record<Device, string[]>;
	groups: { name: string; flows: Flow[]; notes: string[] }[];
}
interface Results {
	projects: string[];
	flows: Record<string, Record<string, string[]>>;
}

const list = JSON.parse(readFileSync(FLOWS, 'utf8')) as FlowList;
if (!existsSync(RESULTS)) {
	console.error(`No ${RESULTS}: run the full browser test suite first (npm run test:e2e).`);
	process.exit(1);
}
const results = JSON.parse(readFileSync(RESULTS, 'utf8')) as Results;

const allProjects = Object.values(list.devices).flat();
const missing = allProjects.filter((p) => !results.projects.includes(p));
if (missing.length) {
	console.error(
		`Browser projects missing from this run: ${missing.join(', ')}. Run the full suite.`
	);
	process.exit(1);
}

const flows = list.groups.flatMap((g) => g.flows);
const isCovered = (flow: Flow, device: Device) =>
	list.devices[device].every((project) => (results.flows[flow.id]?.[project] ?? []).length > 0);
const covered = flows.flatMap((f) =>
	f.devices.filter((d) => isCovered(f, d)).map((d) => `${f.id}/${d}`)
);
const total = flows.reduce((n, f) => n + f.devices.length, 0);
const percent = Math.round((100 * covered.length) / total);

function coverageCell(flow: Flow): string {
	const done = flow.devices.filter((d) => isCovered(flow, d));
	if (done.length === flow.devices.length) return 'Covered';
	if (done.length === 0) return 'Gap';
	return flow.devices.map((d) => `${d}: ${done.includes(d) ? 'covered' : 'gap'}`).join(', ');
}

const LABELS: Record<string, string> = {
	chromium: 'Chromium',
	firefox: 'Firefox',
	webkit: 'WebKit',
	'pixel-7': 'Pixel 7',
	'iphone-14': 'iPhone 14'
};
const browsers = (device: Device) =>
	list.devices[device]
		.map((p) => LABELS[p] ?? p)
		.join(', ')
		.replace(/, ([^,]+)$/, ' and $1');
const short = (d: Device) => (d === 'desktop' ? 'D' : 'P');
const gaps = flows.filter((f) => coverageCell(f) !== 'Covered');
const headline = `**${covered.length} of ${total} flow-by-device pairs covered (${percent}%).** ${flows.length - gaps.length} of ${flows.length} flows are covered on every device they need.`;

// The CI summary: the headline and the gaps, by name.
const summary = [
	'## User flow coverage',
	'',
	headline,
	'',
	gaps.length ? `**Gaps (${gaps.length}):**` : 'No gaps.',
	...gaps.map(
		(f) => `- ${f.id} ${f.name}: ${coverageCell(f) === 'Gap' ? 'no tests yet' : coverageCell(f)}`
	)
].join('\n');
console.log(summary);
if (process.env.GITHUB_STEP_SUMMARY)
	appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary + '\n');

function doc(): string {
	const out = [
		'# User flows',
		'',
		'Every goal a person can achieve in Cold Open, and the devices each one must be proven on. Code coverage shows which lines ran. This list shows whether each **user goal** works, on each device.',
		'',
		`*Generated by \`npm run flows:update\` from a full browser test run. Don't edit it by hand: the flow list is [\`e2e/flows.json\`](../e2e/flows.json), and a browser test proves a flow by tagging it, for example \`{ tag: '@F05' }\`. CI fails if a covered pair loses its test.*`,
		'',
		`**Devices:** **D** = desktop (${browsers('desktop')}). **P** = phone (${browsers('phone')} sizes, with touch). A flow is covered on a device only when it passes in every browser listed for that device.`
	];
	for (const group of list.groups) {
		out.push(
			'',
			`## ${group.name}`,
			'| ID | Flow | Devices | Story | Coverage |',
			'|---|---|---|---|---|'
		);
		for (const f of group.flows) {
			out.push(
				`| ${f.id} | ${f.name} | ${f.devices.map(short).join(', ')} | ${f.stories} | ${coverageCell(f)} |`
			);
		}
		for (const note of group.notes) out.push('', note);
	}
	out.push('', '## Tests behind each flow');
	const proven = flows.filter((f) => results.flows[f.id]);
	if (!proven.length) out.push('', 'None yet.');
	for (const f of proven) {
		const tests = [...new Set(Object.values(results.flows[f.id]).flat())].sort();
		out.push('', `**${f.id}** ${f.name}`, ...tests.map((t) => `- \`${t}\``));
	}
	out.push('', '## Summary', headline);
	return out.join('\n') + '\n';
}

const baseline = (JSON.parse(readFileSync(BASELINE, 'utf8')) as { covered: string[] }).covered;
const lost = baseline.filter((pair) => !covered.includes(pair));
const gained = covered.filter((pair) => !baseline.includes(pair));
const updating = process.argv.includes('--update');
if (gained.length)
	console.log(
		`\nNewly covered${updating ? '' : ' (accept with npm run flows:update)'}: ${gained.join(', ')}`
	);
if (lost.length) {
	console.error(`\nFlow coverage dropped. No passing test proves: ${lost.join(', ')}`);
	// Accepting a drop must be deliberate, so it can't happen by running --update after a bad run.
	if (!(updating && process.argv.includes('--allow-drop'))) process.exit(1);
}
if (updating) {
	writeFileSync(BASELINE, JSON.stringify({ covered }, null, 2) + '\n');
	writeFileSync(DOC, doc());
	console.log(`\nUpdated ${BASELINE} and ${DOC}.`);
} else {
	console.log('\nFlow coverage guard passed.');
}
